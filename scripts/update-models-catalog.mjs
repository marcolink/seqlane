#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const defaultSourceUrl = "https://models.dev/api.json";
const defaultOpenAIOutputPath =
  "libs/seqlane-core/src/models/providers/openai.generated.ts";
const defaultAnthropicOutputPath =
  "libs/seqlane-core/src/models/providers/anthropic.generated.ts";

const catalogSchema = z.record(
  z.string(),
  z.looseObject({
    models: z.record(z.string(), z.looseObject({ id: z.string().min(1) })),
  }),
);

function usage() {
  console.log(`Usage: node scripts/update-models-catalog.mjs [options]

Options:
  --source <url>    models.dev catalog URL
  --output <path>   generated OpenAI TypeScript output path
  --anthropic-output <path>
                    generated Anthropic TypeScript output path
  --help            show this help
`);
}

function parseArguments(arguments_) {
  const options = {
    source: defaultSourceUrl,
    openAIOutput: defaultOpenAIOutputPath,
    anthropicOutput: defaultAnthropicOutputPath,
  };

  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];
    if (argument === "--help") {
      usage();
      process.exit(0);
    }

    if (
      argument !== "--source" &&
      argument !== "--output" &&
      argument !== "--anthropic-output"
    ) {
      throw new Error(`Unknown argument "${argument}"`);
    }

    const value = arguments_[index + 1];
    if (value === undefined || value.startsWith("--")) {
      throw new Error(`Missing value for ${argument}`);
    }

    if (argument === "--source") options.source = value;
    else if (argument === "--output") options.openAIOutput = value;
    else options.anthropicOutput = value;
    index += 1;
  }

  return options;
}

export async function fetchCatalog(source) {
  const response = await fetch(source, {
    signal: AbortSignal.timeout(30_000),
    headers: { accept: "application/json" },
  });
  if (!response.ok) {
    throw new Error(`Catalog request failed with HTTP ${response.status}`);
  }

  let value;
  try {
    value = JSON.parse(await response.text());
  } catch (cause) {
    throw new Error("Catalog response was not valid JSON", { cause });
  }

  const parsed = catalogSchema.safeParse(value);
  if (!parsed.success) {
    throw new Error("Catalog response did not match the expected schema", {
      cause: parsed.error,
    });
  }
  return parsed.data;
}

export function generateProviderFile(source, provider, modelIds) {
  const canonicalCatalog = JSON.stringify({ provider, modelIds });
  const catalogHash = createHash("sha256")
    .update(canonicalCatalog)
    .digest("hex");
  const models = modelIds.map((id) => `  ${JSON.stringify(id)},`).join("\n");
  const providerName = provider === "openai" ? "OpenAI" : "Anthropic";
  const exportName = provider === "openai" ? "openAI" : "anthropic";

  return `/**
 * Generated by scripts/update-models-catalog.mjs.
 * Source: ${source}
 * Catalog hash: sha256:${catalogHash}
 * Do not edit manually.
 */
export const ${exportName}ModelIds = [
${models}
] as const;

export type ${providerName}ModelId = (typeof ${exportName}ModelIds)[number];
`;
}

export function getModelIds(catalog, provider) {
  const providerCatalog = catalog[provider];
  if (providerCatalog === undefined) {
    throw new Error(`Catalog does not contain the "${provider}" provider`);
  }

  return Object.entries(providerCatalog.models)
    .map(([catalogId, model]) => {
      if (catalogId !== model.id) {
        throw new Error(
          `${provider} catalog key "${catalogId}" does not match model ID "${model.id}"`,
        );
      }
      return model.id;
    })
    .sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
}

async function writeIfChanged(outputPath, output) {
  let previous;
  try {
    previous = await readFile(outputPath, "utf8");
  } catch (cause) {
    if (cause?.code !== "ENOENT") throw cause;
  }

  if (previous === output) return false;

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  return true;
}

export async function updateCatalog() {
  const options = parseArguments(process.argv.slice(2));
  const catalog = await fetchCatalog(options.source);
  const outputs = [
    {
      provider: "openai",
      name: "OpenAI",
      path: options.openAIOutput,
    },
    {
      provider: "anthropic",
      name: "Anthropic",
      path: options.anthropicOutput,
    },
  ];

  for (const { provider, name, path } of outputs) {
    const modelIds = getModelIds(catalog, provider);
    const output = generateProviderFile(options.source, provider, modelIds);
    const outputPath = resolve(repositoryRoot, path);
    const changed = await writeIfChanged(outputPath, output);

    console.log(
      `${changed ? "Updated" : "Unchanged"} ${path} with ${modelIds.length} ${name} model IDs`,
    );
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  updateCatalog().catch((cause) => {
    console.error(cause instanceof Error ? cause.message : cause);
    process.exitCode = 1;
  });
}
